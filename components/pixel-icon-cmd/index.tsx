const FRAMES = 38;
const TOTAL = 1024;

function buildKeyframes(): string {
  const decay = [1, 0.7, 0.45, 0.25];
  const rules: string[] = [];
  for (const [idxStr, pulses] of Object.entries(PULSES)) {
    const timeline = new Array(FRAMES).fill(0.24);
    for (const p of pulses) {
      for (let i = 0; i < decay.length; i++) {
        timeline[(p + i) % FRAMES] = decay[i];
      }
    }
    const frames = timeline
      .map((opacity, f) => {
        const start = ((f / FRAMES) * 100).toFixed(2);
        const end = (((f + 1) / FRAMES) * 100 - 0.01).toFixed(2);
        return `${start}%,${end}%{opacity:${opacity}}`;
      })
      .join("");
    rules.push(`@keyframes pi-cmd-${idxStr}{${frames}}`);
  }
  return rules.join("");
}

interface PixelIconCmdProps {
  className?: string;
}

export function PixelIconCmd({ className }: PixelIconCmdProps) {
  const keyframes = useMemo(buildKeyframes, []);
  const mask = useMemo(
    () => new Set(Object.keys(PULSES).map(Number)),
    [],
  );

  const cells = [];
  for (let i = 0; i < TOTAL; i++) {
    cells.push(
      <div
        key={i}
        className={mask.has(i) ? `px on px-${i}` : "px"}
      />,
    );
  }

  return (
    <>
      <style dangerouslySetInnerHTML={{ __html: keyframes }} />
      <div className={`pixel-icon pixel-icon--cmd ${className ?? ""}`.trim()}>
        {cells}
      </div>
    </>
  );
}

export default PixelIconCmd;
